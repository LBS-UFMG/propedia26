BASE = "https://files.rcsb.org/download/"
UA = "Propedia26/1.0 (academic structural database)"
CODIGO = re.compile(r"^([0-9A-Za-z]{4})[-_.]")


def ids_de_dir(raiz):
    """Extrai o codigo PDB do nome dos arquivos (1A0N-A-B.pdb -> 1A0N)."""
    achados = set()
    for dirpath, _dirnames, filenames in os.walk(raiz):
        for f in filenames:
            if f.lower().endswith((".pdb", ".ent", ".cif")):
                m = CODIGO.match(f)
                if m:
                    achados.add(m.group(1).upper())
    return achados


def ids_de_csv(caminho):
    import csv
    csv.field_size_limit(min(sys.maxsize, 2**31 - 1))
    achados = set()
    with open(caminho, newline="", encoding="utf-8", errors="replace") as fh:
        amostra = fh.read(8192); fh.seek(0)
        delim = ";" if amostra.count(";") > amostra.count(",") else ","
        for row in csv.DictReader(fh, delimiter=delim):
            v = (row.get("id") or "").strip()
            if len(v) >= 4:
                achados.add(v[:4].upper())
    return achados


def baixa_um(pdb_id, destino, timeout, tentativas=3):
    """Devolve (id, formato, bytes, erro). formato: 'pdb', 'cif' ou None."""
    for ext, fmt in ((".pdb.gz", "pdb"), (".cif.gz", "cif")):
        alvo = os.path.join(destino, pdb_id + ext)
        if os.path.exists(alvo) and os.path.getsize(alvo) > 0:
            return (pdb_id, fmt, os.path.getsize(alvo), None)
    ultimo = ""
    for ext, fmt in ((".pdb.gz", "pdb"), (".cif.gz", "cif")):
        url = BASE + pdb_id + ext
        alvo = os.path.join(destino, pdb_id + ext)
        for t in range(tentativas):
            try:
                req = urllib.request.Request(url, headers={"User-Agent": UA})
                with urllib.request.urlopen(req, timeout=timeout) as r:
                    dados = r.read()
                tmp = alvo + ".part"
                with open(tmp, "wb") as fh:
                    fh.write(dados)
                os.replace(tmp, alvo)
                return (pdb_id, fmt, len(dados), None)
            except urllib.error.HTTPError as e:
                ultimo = "HTTP %s" % e.code
                if e.code == 404:
                    break                      # nao existe nesse formato
                time.sleep(1.5 * (t + 1))      # 429/503: espera crescente
            except Exception as e:
                ultimo = str(e)[:120]
                time.sleep(1.5 * (t + 1))
    return (pdb_id, None, 0, ultimo or "falhou")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--from-dir", help="pasta com arquivos por par (ex.: /pdb)")
    g.add_argument("--from-csv", help="planilha do Propedia com a coluna 'id'")
    g.add_argument("--ids", help="arquivo com um PDB ID por linha")
    g.add_argument("--embutida", action="store_true",
                   help="usa a lista dos 20183 PDB IDs do Propedia 26 embutida neste arquivo")
    ap.add_argument("-o", "--out", default="pdb_full")
    ap.add_argument("-j", "--jobs", type=int, default=20,
                    help="downloads simultaneos (padrao 20; 40 e seguro, evite passar disso)")
    ap.add_argument("--timeout", type=int, default=60)
    ap.add_argument("--limit", type=int, help="baixa so os N primeiros (para testar)")
    args = ap.parse_args()

    if args.embutida:
        ids = set(gzip.decompress(base64.b64decode(IDS_EMBUTIDOS)).decode().split())
        origem = "lista embutida (Propedia 26)"
    elif args.from_dir:
        if not os.path.isdir(args.from_dir):
            sys.exit("ERRO: pasta nao encontrada: %s" % args.from_dir)
        ids = ids_de_dir(args.from_dir)
        origem = "pasta %s" % args.from_dir
    elif args.from_csv:
        if not os.path.isfile(args.from_csv):
            sys.exit("ERRO: arquivo nao encontrado: %s" % args.from_csv)
        ids = ids_de_csv(args.from_csv)
        origem = "csv %s" % args.from_csv
    else:
        ids = {l.strip().upper() for l in open(args.ids) if l.strip()}
        origem = "lista %s" % args.ids

    ids = sorted(ids)
    if not ids:
        sys.exit("ERRO: nenhum PDB ID encontrado em %s" % origem)
    if args.limit:
        ids = ids[:args.limit]
    os.makedirs(args.out, exist_ok=True)

    ja = {f.split(".")[0] for f in os.listdir(args.out)
          if f.endswith(".pdb.gz") or f.endswith(".cif.gz")}
    pendentes = [i for i in ids if i not in ja]

    print("origem   : %s" % origem)
    print("PDB IDs  : %d unicos" % len(ids))
    print("ja tenho : %d" % len(ja))
    print("baixar   : %d" % len(pendentes))
    print("destino  : %s" % os.path.abspath(args.out))
    print("paralelo : %d\n" % args.jobs, flush=True)
    if not pendentes:
        print("nada a fazer."); return

    lock = threading.Lock()
    cont = {"pdb": 0, "cif": 0, "erro": 0, "bytes": 0}
    falhas = []
    inicio = time.time()
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futs = [pool.submit(baixa_um, i, args.out, args.timeout) for i in pendentes]
        for n, fut in enumerate(as_completed(futs), 1):
            pid, fmt, tam, err = fut.result()
            with lock:
                if fmt:
                    cont[fmt] += 1; cont["bytes"] += tam
                else:
                    cont["erro"] += 1; falhas.append((pid, err))
            if n % 250 == 0 or n == len(pendentes):
                dec = time.time() - inicio
                taxa = n / dec if dec else 0
                print("  %d/%d  pdb=%d cif=%d erro=%d  %.1f arq/s  %.2f GB  faltam ~%.0f min"
                      % (n, len(pendentes), cont["pdb"], cont["cif"], cont["erro"], taxa,
                         cont["bytes"] / 1e9, (len(pendentes) - n) / taxa / 60 if taxa else 0),
                      flush=True)

    print("\nconcluido em %.1f min | %.2f GB" % ((time.time() - inicio) / 60, cont["bytes"] / 1e9))
    print("pdb: %d | cif: %d | falhas: %d" % (cont["pdb"], cont["cif"], cont["erro"]))
    if falhas:
        with open("download_falhas.txt", "w") as fh:
            for pid, err in falhas:
                fh.write("%s\t%s\n" % (pid, err))
        print("falhas em download_falhas.txt (rode de novo para tentar so elas)")


if __name__ == "__main__":
    main()
