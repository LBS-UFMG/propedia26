def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pasta")
    ap.add_argument("--mover", help="pasta para onde mover as nao cristalograficas")
    a = ap.parse_args()
    xray = set(gzip.decompress(base64.b64decode(IDS)).decode().split())
    arqs = [f for f in os.listdir(a.pasta) if f.endswith((".pdb.gz", ".cif.gz", ".pdb", ".cif"))]
    fica = [f for f in arqs if f.split(".")[0].upper() in xray]
    sai = [f for f in arqs if f.split(".")[0].upper() not in xray]
    print("arquivos na pasta      : %d" % len(arqs))
    print("difracao (manter)      : %d" % len(fica))
    print("crio-EM/RMN (pular)    : %d" % len(sai))
    if a.mover:
        os.makedirs(a.mover, exist_ok=True)
        for f in sai:
            shutil.move(os.path.join(a.pasta, f), os.path.join(a.mover, f))
        print("\nmovidos %d arquivos para %s" % (len(sai), a.mover))
        print("restam %d estruturas para processar" % len(fica))
    else:
        print("\n(nada foi movido; use --mover pdb_outros)")

if __name__ == "__main__":
    main()
